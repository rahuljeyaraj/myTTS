"""Writes what packaging/mytts.iss needs into a folder (build/installer by default).

- defines.iss: the version, names, app id and the voice-model files (URL, size, SHA-256),
  all taken from the Python code so the installer can't drift from the app.
- The setup icon and the wizard images, drawn from the app icon.

Run by packaging/build.ps1 -Installer before the Inno Setup compiler.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from PySide6.QtCore import QRectF, Qt  # noqa: E402
from PySide6.QtGui import QColor, QImage, QPainter  # noqa: E402

from mytts import DISPLAY_NAME, PROJECT_URL, __version__, models  # noqa: E402
from mytts.settings import DEFAULT_HOTKEY  # noqa: E402
from mytts.ui import native  # noqa: E402
from mytts.ui.icon import INK, render, save_ico  # noqa: E402

PUBLISHER = "rahuljeyaraj"
# Sizes Inno Setup picks from: the small image is square, the large one is 164:314.
SMALL = (58, 77, 97, 116, 124, 143, 159)
LARGE = ((164, 314), (202, 386), (240, 459), (328, 628))


def _large(w: int, h: int) -> QImage:
    img = QImage(w, h, QImage.Format.Format_ARGB32_Premultiplied)
    img.fill(QColor(INK))
    icon = render(int(w * 0.5))
    p = QPainter(img)
    p.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform)
    p.drawImage(QRectF((w - icon.width()) / 2, h * 0.36 - icon.height() / 2, icon.width(), icon.height()), icon)
    p.end()
    return img


def _iss(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def write(out: Path) -> Path:
    out = out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    save_ico(out / "mytts.ico")
    small = []
    for s in SMALL:
        path = out / f"small-{s}.png"
        render(s).save(str(path))
        small.append(path)
    large = []
    for w, h in LARGE:
        path = out / f"large-{w}.png"
        _large(w, h).save(str(path))
        large.append(path)

    base_url = models.MODEL.url.rsplit("/", 1)[0]
    copyright_line = next(line for line in (ROOT / "LICENSE").read_text(encoding="utf-8").splitlines()
                          if line.startswith("Copyright"))
    defines = {
        "AppName": DISPLAY_NAME,
        "AppVersion": __version__,
        "AppPublisher": PUBLISHER,
        "ProjectUrl": PROJECT_URL,
        "Copyright": copyright_line,
        "ReadHotkey": DEFAULT_HOTKEY,
        "AppUserModelID": native.APP_ID,
        "SetupIcon": str(out / "mytts.ico"),
        "SmallImages": ",".join(str(p) for p in small),
        "LargeImages": ",".join(str(p) for p in large),
        "ModelBaseUrl": base_url,
        "ModelName": models.MODEL.name,
        "ModelSize": str(models.MODEL.size),
        "ModelSha256": models.MODEL.sha256,
        "VoicesName": models.VOICES.name,
        "VoicesSize": str(models.VOICES.size),
        "VoicesSha256": models.VOICES.sha256,
        "ModelMB": str(round(sum(f.size for f in models.REQUIRED) / 1e6)),
    }
    lines = ["; Generated by packaging/installer_assets.py. Do not edit."]
    lines += [f"#define {k} {_iss(v)}" for k, v in defines.items()]
    path = out / "defines.iss"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


if __name__ == "__main__":
    print(write(Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "build" / "installer"))
